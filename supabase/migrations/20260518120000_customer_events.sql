-- Oportunidades (deals) existentes
insert into public.customer_events (
    contact_id, business_line_id, type, occurred_at, payload,
    source, sales_id, related_table, related_id
)
select
    unnest(d.contact_ids) as contact_id,
    d.company_id,
    'opportunity.created',
    coalesce(d.created_at, now()),
    jsonb_build_object(
        'name', d.name,
        'stage', d.stage,
        'amount', d.amount
    ),
    'system',
    d.sales_id,
    'deals',
    d.id
from public.deals d
where d.contact_ids is not null and array_length(d.contact_ids, 1) > 0
  and not exists (
      select 1
      from public.customer_events ce
      where ce.related_table = 'deals'
        and ce.related_id = d.id
        and ce.type = 'opportunity.created'
  )
on conflict do nothing;

