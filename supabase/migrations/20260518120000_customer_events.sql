-- Función genérica para resolver business_line_id desde un contact_id
create or replace function public.resolve_business_line_from_contact(p_contact_id bigint)
returns bigint
language sql
stable
security invoker
set search_path = public
as $$
    select company_id from public.contacts where id = p_contact_id
$$;

-- ---- contact_notes → note.created ----
create or replace function public.tg_customer_events_from_contact_note()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
    insert into public.customer_events (
        contact_id,
        business_line_id,
        type,
        occurred_at,
        payload,
        source,
        sales_id,
        related_table,
        related_id
    )
    values (
        new.contact_id,
        public.resolve_business_line_from_contact(new.contact_id),
        'note.created',
        coalesce(new.date, now()),
        jsonb_build_object(
            'preview', left(coalesce(new.text, ''), 200),
            'status', new.status
        ),
        'system',
        new.sales_id,
        'contact_notes',
        new.id
    );
    return new;
end;
$$;

create trigger customer_events_from_contact_note
    after insert on public.contact_notes
    for each row
    execute function public.tg_customer_events_from_contact_note();

-- ---- tasks → task.created / task.completed ----
create or replace function public.tg_customer_events_from_task()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
    if (TG_OP = 'INSERT') then
        insert into public.customer_events (
            contact_id, business_line_id, type, occurred_at, payload,
            source, sales_id, related_table, related_id
        )
        values (
            new.contact_id,
            public.resolve_business_line_from_contact(new.contact_id),
            'task.created',
            coalesce(new.due_date, now()),
            jsonb_build_object(
                'title', new.text,
                'due_date', new.due_date,
                'type', new.type
            ),
            'system',
            new.sales_id,
            'tasks',
            new.id
        );
    elsif (TG_OP = 'UPDATE'
           and old.done_date is null
           and new.done_date is not null) then
        insert into public.customer_events (
            contact_id, business_line_id, type, occurred_at, payload,
            source, sales_id, related_table, related_id
        )
        values (
            new.contact_id,
            public.resolve_business_line_from_contact(new.contact_id),
            'task.completed',
            new.done_date,
            jsonb_build_object('title', new.text),
            'system',
            new.sales_id,
            'tasks',
            new.id
        );
    end if;
    return new;
end;
$$;

create trigger customer_events_from_task
    after insert or update on public.tasks
    for each row
    execute function public.tg_customer_events_from_task();

-- ---- appointments → appointment.created / completed / cancelled ----
create or replace function public.tg_customer_events_from_appointment()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
    if (TG_OP = 'INSERT') then
        insert into public.customer_events (
            contact_id, business_line_id, type, occurred_at, payload,
            source, related_table, related_id
        )
        values (
            new.contact_id,
            public.resolve_business_line_from_contact(new.contact_id),
            case new.status
                when 'completed' then 'appointment.completed'
                when 'cancelled' then 'appointment.cancelled'
                else 'appointment.created'
            end,
            new.scheduled_at,
            jsonb_build_object(
                'type', new.type,
                'status', new.status,
                'scheduled_at', new.scheduled_at
            ),
            'system',
            'appointments',
            new.id
        );
    elsif (
        TG_OP = 'UPDATE'
        and old.status is distinct from new.status
        and new.status in ('completed', 'cancelled')
    ) then
        insert into public.customer_events (
            contact_id, business_line_id, type, occurred_at, payload,
            source, related_table, related_id
        )
        values (
            new.contact_id,
            public.resolve_business_line_from_contact(new.contact_id),
            case new.status
                when 'completed' then 'appointment.completed'
                else 'appointment.cancelled'
            end,
            coalesce(new.updated_at, now()),
            jsonb_build_object(
                'type', new.type,
                'status', new.status,
                'scheduled_at', new.scheduled_at
            ),
            'system',
            'appointments',
            new.id
        );
    end if;

    return new;
end;
$$;

do $$
begin
    if exists (
        select 1
        from information_schema.tables
        where table_schema = 'public'
          and table_name = 'appointments'
    ) then
        execute 'drop trigger if exists customer_events_from_appointment on public.appointments';
        execute 'create trigger customer_events_from_appointment
                 after insert or update on public.appointments
                 for each row
                 execute function public.tg_customer_events_from_appointment()';
    else
        raise notice 'Tabla public.appointments no existe - trigger de appointments OMITIDO. Aplicar 20260516201500_appointments_entity.sql primero.';
    end if;
end $$;

-- ---- deals → opportunity.created / opportunity.stage_changed ----
-- Nota: deals están reinterpretados como "opportunities" en Claridad.
-- Como deals.contact_ids es un array, escribimos un evento por cada contacto.
create or replace function public.tg_customer_events_from_deal()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
declare
    v_contact_id bigint;
begin
    if (TG_OP = 'INSERT') then
        if new.contact_ids is not null then
            foreach v_contact_id in array new.contact_ids loop
                insert into public.customer_events (
                    contact_id, business_line_id, type, occurred_at, payload,
                    source, sales_id, related_table, related_id
                )
                values (
                    v_contact_id,
                    new.company_id,
                    'opportunity.created',
                    coalesce(new.created_at, now()),
                    jsonb_build_object(
                        'name', new.name,
                        'stage', new.stage,
                        'amount', new.amount
                    ),
                    'system',
                    new.sales_id,
                    'deals',
                    new.id
                );
            end loop;
        end if;
    elsif (TG_OP = 'UPDATE' and old.stage is distinct from new.stage) then
        if new.contact_ids is not null then
            foreach v_contact_id in array new.contact_ids loop
                insert into public.customer_events (
                    contact_id, business_line_id, type, occurred_at, payload,
                    source, sales_id, related_table, related_id
                )
                values (
                    v_contact_id,
                    new.company_id,
                    'opportunity.stage_changed',
                    now(),
                    jsonb_build_object(
                        'name', new.name,
                        'from_stage', old.stage,
                        'to_stage', new.stage
                    ),
                    'system',
                    new.sales_id,
                    'deals',
                    new.id
                );
            end loop;
        end if;
    end if;
    return new;
end;
$$;

create trigger customer_events_from_deal
    after insert or update on public.deals
    for each row
    execute function public.tg_customer_events_from_deal();

