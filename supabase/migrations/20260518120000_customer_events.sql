-- Notas existentes
insert into public.customer_events (
    contact_id, business_line_id, type, occurred_at, payload,
    source, sales_id, related_table, related_id
)
select
    cn.contact_id,
    c.company_id,
    'note.created',
    coalesce(cn.date, now()),
    jsonb_build_object(
        'preview', left(coalesce(cn.text, ''), 200),
        'status', cn.status
    ),
    'system',
    cn.sales_id,
    'contact_notes',
    cn.id
from public.contact_notes cn
left join public.contacts c on c.id = cn.contact_id
where not exists (
    select 1
    from public.customer_events ce
    where ce.related_table = 'contact_notes'
      and ce.related_id = cn.id
      and ce.type = 'note.created'
)
on conflict do nothing;

-- Tareas creadas existentes
insert into public.customer_events (
    contact_id, business_line_id, type, occurred_at, payload,
    source, sales_id, related_table, related_id
)
select
    t.contact_id,
    c.company_id,
    'task.created',
    -- tasks no tiene created_at en el esquema base de Atomic;
    -- usamos due_date como aproximación o now() si es null.
    coalesce(t.due_date, now()),
    jsonb_build_object(
        'title', t.text,
        'due_date', t.due_date,
        'type', t.type
    ),
    'system',
    t.sales_id,
    'tasks',
    t.id
from public.tasks t
left join public.contacts c on c.id = t.contact_id
where not exists (
    select 1
    from public.customer_events ce
    where ce.related_table = 'tasks'
      and ce.related_id = t.id
      and ce.type = 'task.created'
)
on conflict do nothing;

-- Tareas ya completadas
insert into public.customer_events (
    contact_id, business_line_id, type, occurred_at, payload,
    source, sales_id, related_table, related_id
)
select
    t.contact_id,
    c.company_id,
    'task.completed',
    t.done_date,
    jsonb_build_object('title', t.text),
    'system',
    t.sales_id,
    'tasks',
    t.id
from public.tasks t
left join public.contacts c on c.id = t.contact_id
where t.done_date is not null
  and not exists (
      select 1
      from public.customer_events ce
      where ce.related_table = 'tasks'
        and ce.related_id = t.id
        and ce.type = 'task.completed'
  )
on conflict do nothing;

