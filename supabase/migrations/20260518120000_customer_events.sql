-- ============================================================================
-- customer_events — append-only timeline backbone
-- ============================================================================
-- Cada fila representa UN evento de relación con una clienta.
-- Esta tabla alimenta:
--   1. Timeline unificado por clienta (vista "todo lo que pasó con Laura")
--   2. Pantalla "Hoy" (qué requiere acción)
--   3. Cohortes (clientas sin contacto >30 días, etc.)
--   4. Auditoría e histórico operativo
--
-- Reglas:
--   * Append-only (no updates ni deletes en lógica de aplicación)
--   * Una fila por evento atómico
--   * payload jsonb para datos específicos del tipo
--   * Triggers desde contact_notes, tasks, appointments, deals la alimentan
--
-- PREREQUISITOS (deben aplicarse antes que esta migración):
--   * 20260516183000_contact_profile_fields.sql (birthday, whatsapp, business_lines_interest)
--   * 20260516201500_appointments_entity.sql    (tabla appointments)
-- El trigger de appointments y el backfill de appointments se ejecutan
-- condicionalmente si la tabla existe, así que esta migración es defensiva.
-- ============================================================================

create table if not exists public.customer_events (
    id bigint generated by default as identity primary key,
    contact_id bigint not null,
    business_line_id bigint,
    type text not null,
    occurred_at timestamp with time zone not null default now(),
    payload jsonb not null default '{}'::jsonb,
    source text not null default 'system',
    sales_id bigint,
    related_table text,
    related_id bigint,
    created_at timestamp with time zone not null default now()
);

-- ----------------------------------------------------------------------------
-- Foreign keys
-- ----------------------------------------------------------------------------

alter table public.customer_events
    add constraint customer_events_contact_id_fkey
    foreign key (contact_id) references public.contacts(id)
    on update cascade on delete cascade;

-- business_line_id apunta a companies (reinterpretadas como líneas de negocio
-- en el dominio Claridad). Se permite null porque hay eventos sin línea.
alter table public.customer_events
    add constraint customer_events_business_line_id_fkey
    foreign key (business_line_id) references public.companies(id)
    on update cascade on delete set null;

alter table public.customer_events
    add constraint customer_events_sales_id_fkey
    foreign key (sales_id) references public.sales(id)
    on update cascade on delete set null;

