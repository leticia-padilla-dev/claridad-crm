-- ----------------------------------------------------------------------------
-- Indexes
-- ----------------------------------------------------------------------------

-- Timeline por clienta (query más frecuente)
create index if not exists customer_events_contact_id_occurred_at_idx
    on public.customer_events using btree (contact_id, occurred_at desc);

-- "Última actividad por clienta" (cohorte de reactivación)
create index if not exists customer_events_contact_id_idx
    on public.customer_events using btree (contact_id);

-- Filtros por tipo (e.g. listar todos los whatsapp.opened de la semana)
create index if not exists customer_events_type_occurred_at_idx
    on public.customer_events using btree (type, occurred_at desc);

-- Filtros por línea de negocio
create index if not exists customer_events_business_line_id_idx
    on public.customer_events using btree (business_line_id)
    where business_line_id is not null;

create index if not exists customer_events_related_record_idx
    on public.customer_events using btree (related_table, related_id)
    where related_id is not null;

create index if not exists customer_events_sales_id_occurred_at_idx
    on public.customer_events using btree (sales_id, occurred_at desc)
    where sales_id is not null;

